import assert from 'node:assert/strict';

const reserved = new Set([...Object.getOwnPropertyNames(Object.prototype), 'pages', 'mutate', 'then', 'toJSON', 'prototype']);
/** A deliberately bounded generator for this pinned read cohort, not arbitrary OpenAPI. */
export function renderReadClient(input, paths, mutations = []) {
  assert.deepEqual(Object.keys(input.paths), paths, 'named_client_cohort_paths');
  assert.equal(paths.length, 11, 'named_client_operation_count');
  const seen = new Set();
  const methods = paths.map(path => {
    const item = input.paths[path];
    assert.ok(item && Object.keys(item).every(key => key === 'get' || key === 'parameters'), 'named_client_get_only');
    const operation = item.get;
    assert.ok(operation && !operation.requestBody && !operation.servers && !item.servers, 'named_client_operation_shape');
    const name = operation.operationId;
    assert.ok(typeof name === 'string' && /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && !reserved.has(name), 'named_client_identifier');
    assert.equal(seen.has(name), false, 'named_client_duplicate_identifier');
    seen.add(name);
    const parameters = [...(item.parameters ?? []), ...(operation.parameters ?? [])];
    assert.ok(parameters.every(p => p && !p.$ref && ['path', 'query'].includes(p.in) && typeof p.name === 'string' && typeof p.required === 'boolean' && p.schema), 'named_client_parameter_shape');
    assert.ok(parameters.every(p => p.in !== 'path' || p.required === true), 'named_client_path_required');
    assert.equal(new Set(parameters.map(p => `${p.in}:${p.name}`)).size, parameters.length, 'named_client_parameter_override_not_supported');
    const required = parameters.some(p => p.required);
    return { method: name, operationId: name, httpMethod: 'GET', path, inputRequired: required };
  });
  assert.deepEqual(mutations.map(item => [item.operationId, item.method, item.path, item.successStatus]), mutations.length ? [
    ['postEndUsers', 'POST', '/end-users', 201], ['patchEndUsersById', 'PATCH', '/end-users/{id}', 200],
  ] : [], 'named_client_mutation_cohort');
  const banner = `// Generated by generate-client.mjs from the pinned eleven-read${mutations.length ? ' and two-write projections' : ' projection'}. Do not edit.\n`;
  const client = `${banner}import { createReadPrototype } from '../runtime.ts';
import type { PrototypeOptions, RequestOptions, PageOptions, PageOperation, ReadInput, ReadResult, ReadData } from '../runtime.ts';
${mutations.length ? "import type { MutationOperation, MutationInput, MutationResult, MutationRequestOptions } from '../mutation-contract.ts';\n" : ''}

export class BotaApiClient {
  readonly #runtime: ReturnType<typeof createReadPrototype>;

  constructor(options: PrototypeOptions) {
    this.#runtime = createReadPrototype(options);
  }
${methods.map(m => `
  ${m.method}(input${m.inputRequired ? '' : '?'}: ReadInput<'${m.operationId}'>, options?: RequestOptions): Promise<ReadResult<'${m.operationId}'>> {
    return this.#runtime.read('${m.operationId}', input, options);
  }
`).join('')}${mutations.map(m => `
  ${m.operationId}(input: MutationInput<'${m.operationId}'>, options?: MutationRequestOptions): Promise<MutationResult<'${m.operationId}'>> {
    return this.#runtime.mutate('${m.operationId}', input, options);
  }
`).join('')}${mutations.length ? `
  mutate<O extends MutationOperation>(operation: O, input: MutationInput<O>, options?: MutationRequestOptions): Promise<MutationResult<O>> {
    return this.#runtime.mutate(operation, input, options);
  }
` : ''}
  pages<O extends PageOperation>(operation: O, input?: ReadInput<O>, options?: PageOptions): AsyncGenerator<ReadData<O>, void, unknown> {
    return this.#runtime.pages(operation, input, options);
  }
}
`;
  // Keep every existing factory/error/type export. Named methods add a surface;
  // they do not substitute a second transport, credential store or retry policy.
  const entry = `${banner}export { BotaApiClient } from './generated/client.ts';
export * from './runtime.ts';
export type { components, operations, paths } from './generated/schema.d.ts';
${mutations.length ? "export type { MutationOperation, MutationInput, MutationData, MutationResult, MutationRequestOptions } from './mutation-contract.ts';\nexport type { components as mutationComponents, operations as mutationOperations, paths as mutationPaths } from './generated/mutations-schema.d.ts';" : ''}
`.trimEnd() + '\n';
  return { client, entry, methods };
}
