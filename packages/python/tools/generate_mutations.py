"""Generate two separately pinned ordinary mutations; preserve original read outputs."""
from __future__ import annotations

import argparse
import copy
import gzip
import importlib.util
import json
from pathlib import Path
import re

SPEC = importlib.util.spec_from_file_location("read_generation", Path(__file__).with_name("generate.py"))
assert SPEC is not None and SPEC.loader is not None
read = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(read)
require, digest, json_bytes = read.require, read.digest, read.json_bytes
OUTPUT = read.OUTPUT / "mutations"
ADMITTED = (
    {"operationId": "postEndUsers", "method": "POST", "path": "/end-users", "successStatus": 201},
    {"operationId": "patchEndUsersById", "method": "PATCH", "path": "/end-users/{id}", "successStatus": 200},
)
BANNER = "# Generated by tools/generate_mutations.py from the pinned ordinary-mutation projection. Do not edit.\n"
# Frozen independently of the original eleven-read pins.
PINS = {
    "mutation-cohort.json": "875af802fbb5e9da2a52d1905a0abd01187c1de41cb5edc26a149314b83c22d1",
    "mutation-input.json": "3b7c5d595c0caa47989ee6ec0f1bd0fd2e12e1fab8eecba4efc182d1a16afb89",
    "mutation-source-openapi.json.gz": "50e21831a76d4076eaf9519d9c49eb0b78c3af58ebd37ca416ebc268fdd84936",
    "mutations/corpus.json": "c86761f07b77dfa5ea0f87ea1d10497066ab17b801847a3ff518325989c01b91",
    "mutations/policy.json": "8aa3e8c078273db1f657ca51f6e357b41dac0fe401b4b508dc1c8261b163dcbd",
}


def project(source: dict) -> dict:
    require(source.get("openapi") == "3.1.0" and source["servers"][0]["url"] == "https://api.bota.dev/v1", "mutation_source_identity")
    result = {name: copy.deepcopy(source[name]) for name in ("openapi", "info", "servers")}
    result.update(paths={}, components={}, security=copy.deepcopy(source["security"]))
    for admitted in ADMITTED:
        item = source["paths"][admitted["path"]]
        method = admitted["method"].lower()
        definition = item[method]
        require(definition["operationId"] == admitted["operationId"] and not item.get("servers")
                and not definition.get("servers"), "mutation_source_operation")
        validate_operation(item, definition, admitted)
        result["paths"][admitted["path"]] = {**({"parameters": copy.deepcopy(item["parameters"])} if "parameters" in item else {}), method: copy.deepcopy(definition)}
    seen: set[str] = set()

    def add(ref: str) -> None:
        require(isinstance(ref, str) and re.fullmatch(r"#/components/(schemas|responses|headers|parameters|securitySchemes)/[^/]+", ref), "mutation_nonlocal_reference")
        if ref in seen:
            return
        seen.add(ref)
        _, _, kind, token = ref.split("/")
        require(not re.search(r"~(?![01])", token), "mutation_reference_encoding")
        name = token.replace("~1", "/").replace("~0", "~")
        require(name in source.get("components", {}).get(kind, {}), "mutation_missing_reference")
        value = copy.deepcopy(source["components"][kind][name])
        result["components"].setdefault(kind, {})[name] = value
        walk(value)

    def walk(value: object) -> None:
        if isinstance(value, list):
            for child in value:
                walk(child)
        elif isinstance(value, dict):
            if "$ref" in value:
                add(value["$ref"])
            for ref in value.get("discriminator", {}).get("mapping", {}).values():
                add(ref)
            for key, child in list(value.items()):
                if key == "security" and isinstance(child, list):
                    for requirement in child:
                        for scheme in requirement:
                            add("#/components/securitySchemes/" + scheme)
                walk(child)

    walk(result)
    return result


def validate_operation(item: dict, operation: dict, admitted: dict) -> None:
    request = operation["requestBody"]
    require(request.get("required") is True and set(request["content"]) == {"application/json"}
            and request["content"]["application/json"]["schema"].get("type") == "object", "mutation_request_contract")
    parameters = [*item.get("parameters", []), *operation.get("parameters", [])]
    require(len(parameters) == int(admitted["method"] == "PATCH")
            and all(parameter.get("in") == "path" and parameter.get("name") == "id"
                    and parameter.get("required") is True and parameter.get("schema") == {"type": "string"}
                    and "$ref" not in parameter for parameter in parameters), "mutation_parameter_contract")
    require([status for status in operation["responses"] if status.startswith("2")] == [str(admitted["successStatus"])], "mutation_success_contract")
    policy = operation.get("x-bota-write-contract", {})
    require(all(policy.get(field) is False for field in ("automatic_retry", "automatic_idempotency_key", "automatic_reconciliation")), "mutation_replay_contract")


def load_inputs() -> tuple[dict, dict, dict[str, str]]:
    blobs: dict[str, bytes] = {}
    names = ("mutation-cohort.json", "mutation-input.json", "mutation-source-openapi.json.gz", "mutations/corpus.json", "mutations/policy.json")
    require(set(PINS) == set(names), "mutation_pins_required")
    for name in names:
        path = read.TYPESCRIPT / name
        require(path.is_file() and not path.is_symlink(), "mutation_nonregular_input")
        blobs[name] = path.read_bytes()
        require(digest(blobs[name]) == PINS[name], "mutation_pinned_input_drift")
    cohort = json.loads(blobs[names[0]])
    require(cohort["version"] == 1 and cohort["operations"] == list(ADMITTED)
            and cohort["baseUrl"] == "https://api.bota.dev/v1", "mutation_cohort_drift")
    require(cohort["source"]["commit"] == "18f48a771b5948677f2d8a4d34d43f68d0d636dd", "mutation_source_commit_drift")
    source = gzip.decompress(blobs[names[2]])
    require(len(source) <= 5 * 1024 * 1024 and digest(source) == cohort["source"]["sha256"], "mutation_source_digest")
    document = json.loads(blobs[names[1]])
    require(digest(blobs[names[1]]) == cohort["projectionSha256"]
            and json_bytes(project(json.loads(source))) == blobs[names[1]], "mutation_projection_drift")
    corpus, policy = json.loads(blobs[names[3]]), json.loads(blobs[names[4]])
    require(corpus["version"] == policy["version"] == 1 and corpus["policy"] == policy["cohort"] == "ordinary-end-user-writes-v1"
            and len(corpus["cases"]) == 36 and len({case["id"] for case in corpus["cases"]}) == 36,
            "mutation_fixture_identity")
    require(policy["operations"] == [row["operationId"] for row in ADMITTED] and policy["attempts"] == 1
            and policy["automaticIdempotencyHeader"] is False and policy["automaticReconciliation"] is False
            and policy["body"] == {"root": "object", "maxDepth": 64, "maxNodes": 100000,
                "maxUtf8Bytes": 1048576, "safeIntegralNumbers": True, "wellFormedUnicode": True}, "mutation_policy_drift")
    return document, cohort, {name: digest(value) for name, value in blobs.items()}


def render(document: dict, cohort: dict) -> dict[str, bytes]:
    require(cohort["operations"] == list(ADMITTED) and list(document["paths"]) == [row["path"] for row in ADMITTED], "mutation_admission_drift")
    renderer = read.Renderer(document["components"]["schemas"])
    for name in renderer.schemas:
        read.identifier(name)
        renderer.component(name)
    definitions = {}
    methods = []
    for admitted in ADMITTED:
        item = document["paths"][admitted["path"]]
        method = admitted["method"].lower()
        require(set(item) <= {method, "parameters"}, "mutation_methods_expanded")
        operation = item[method]
        require(operation["operationId"] == admitted["operationId"], "mutation_operation_identity")
        validate_operation(item, operation, admitted)
        parameters = [*item.get("parameters", []), *operation.get("parameters", [])]
        require(all(parameter.get("in") == "path" and parameter.get("name") == "id"
                    and parameter.get("required") is True and parameter.get("schema") == {"type": "string"}
                    for parameter in parameters), "mutation_parameter_drift")
        require(len(parameters) == int(method == "patch"), "mutation_path_contract")
        request = operation["requestBody"]
        require(set(request["content"]) == {"application/json"}, "mutation_request_media")
        body = request["content"]["application/json"]["schema"]
        require(body.get("type") == "object", "mutation_object_body")
        props = {"body": body}
        if parameters:
            props["path"] = {"type": "object", "properties": {"id": {"type": "string"}}, "required": ["id"], "additionalProperties": False}
        operation_id = admitted["operationId"]
        prefix = read.pascal(operation_id)
        renderer.object_annotation({"type": "object", "properties": props, "required": list(props), "additionalProperties": False}, prefix + "Input")
        response = operation["responses"][str(admitted["successStatus"])]["content"]["application/json"]["schema"]
        annotation = renderer.annotation(response, prefix + "Response")
        if annotation != prefix + "Response":
            renderer.definitions[prefix + "Response"] = f"type {prefix}Response = {annotation}\n"
        definitions[operation_id] = {"path": admitted["path"], "method": admitted["method"],
                                     "parameters": parameters, "success_status": admitted["successStatus"]}
        methods.append({"name": read.snake(operation_id), "operation_id": operation_id,
                        "input": prefix + "Input", "response": prefix + "Response"})
    models = BANNER + "from typing import Literal, NotRequired, TypedDict\n\n"
    models += "type JsonValue = None | bool | int | float | str | list[JsonValue] | dict[str, JsonValue]\n\n"
    models += "\n".join(renderer.definitions.values())
    operations = BANNER + "from types import MappingProxyType\n\nMUTATIONS = MappingProxyType({\n"
    for operation_id, definition in definitions.items():
        parameters = "()" if not definition["parameters"] else "(MappingProxyType({'in': 'path', 'name': 'id', 'required': True, 'schema': MappingProxyType({'type': 'string'})}),)"
        operations += f"    {operation_id!r}: MappingProxyType({{'path': {definition['path']!r}, 'method': {definition['method']!r}, 'success_status': {definition['success_status']!r}, 'parameters': {parameters}}}),\n"
    operations += "})\n"
    return {"__init__.py": BANNER.encode(), "models.py": models.encode(), "operations.py": operations.encode(), "methods.json": json_bytes(methods)}


def generate(check: bool = False) -> None:
    document, cohort, inputs = load_inputs()
    files = render(document, cohort)
    files["provenance.json"] = json_bytes({"version": 1, "status": "python-two-ordinary-mutations-generated-not-qualified",
        "source": cohort["source"], "inputs": inputs, "generatorSha256": digest(Path(__file__).read_bytes()),
        "rendererSha256": digest(Path(read.__file__).read_bytes()), "operationCount": 2, "sharedFixtureCount": 36,
        "outputs": {name: digest(value) for name, value in files.items()},
        "limitations": "Annotation generation only; no runtime response validation, replay contract or publication."})
    if check:
        for name, value in files.items():
            require((OUTPUT / name).is_file() and not (OUTPUT / name).is_symlink()
                    and (OUTPUT / name).read_bytes() == value, "mutation_generated_drift")
    else:
        OUTPUT.mkdir(exist_ok=True)
        require(not OUTPUT.is_symlink(), "mutation_unsafe_output")
        for name, value in files.items():
            require(not (OUTPUT / name).is_symlink(), "mutation_unsafe_output")
            (OUTPUT / name).write_bytes(value)
    print("Verified" if check else "Generated", "two Python ordinary end-user mutations")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
