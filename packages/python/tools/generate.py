def digest(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def json_bytes(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n").encode("utf-8")


def require(condition: object, message: str) -> None:
    if not condition:
        raise ValueError(message)


def identifier(value: object) -> str:
    require(isinstance(value, str) and re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", value)
            and not keyword.iskeyword(value), "unsupported_python_identifier")
    return value


def snake(value: str) -> str:
    return identifier(re.sub(r"(?<!^)(?=[A-Z])", "_", identifier(value)).lower())


def pascal(value: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in identifier(value).split("_"))


def project(source: dict, cohort: dict) -> dict:
    """Mirror the reviewed local-reference closure; never fetch remote references."""
    require(source.get("openapi") == "3.1.0" and source["servers"][0]["url"] == cohort["baseUrl"], "source_contract_mismatch")
    result = {key: source[key] for key in ("openapi", "info", "servers")}
    result.update(paths={}, components={}, security=source["security"])
    for path in cohort["paths"]:
        item = source["paths"][path]
        require(item.get("get", {}).get("operationId") and "servers" not in item and "servers" not in item["get"], "source_operation_drift")
        result["paths"][path] = {**({"parameters": item["parameters"]} if "parameters" in item else {}), "get": item["get"]}
    seen: set[str] = set()
    kinds = {"schemas", "responses", "parameters", "examples", "requestBodies", "headers", "securitySchemes", "links", "callbacks", "pathItems"}

    def add_ref(ref: str) -> None:
        require(isinstance(ref, str) and re.fullmatch(r"#/components/[^/]+/[^/]+", ref), "nonlocal_reference")
        if ref in seen:
            return
        seen.add(ref)
        _, _, kind, encoded = ref.split("/")
        require(kind in kinds and not re.search(r"~(?![01])", encoded), "unsupported_reference")
        name = encoded.replace("~1", "/").replace("~0", "~")
        require(name in source.get("components", {}).get(kind, {}), "missing_reference")
        value = source["components"][kind][name]
        result["components"].setdefault(kind, {})[name] = value
        walk(value)

    def walk(value: object) -> None:
        if isinstance(value, list):
            for child in value:
                walk(child)
        elif isinstance(value, dict):
            if "$ref" in value:
                add_ref(value["$ref"])
            mapping = value.get("discriminator", {}).get("mapping", {})
            for target in mapping.values():
                require(isinstance(target, str) and target.startswith("#/components/schemas/"), "unsupported_discriminator_mapping")
                add_ref(target)
            for key, child in list(value.items()):
                if key == "security" and isinstance(child, list):
                    for requirement in child:
                        for scheme in requirement:
                            add_ref("#/components/securitySchemes/" + scheme.replace("~", "~0").replace("/", "~1"))
                walk(child)

    walk(result)
    return result


class Renderer:
    """Annotations for the explicit schema subset; not a response validator."""

    def __init__(self, schemas: dict):
        self.schemas = schemas
        self.definitions: dict[str, str] = {}
        self.claims: dict[str, dict] = {}
        self.active: set[str] = set()

    def validate(self, schema: object, depth: int = 0) -> None:
        require(isinstance(schema, dict) and depth <= 48 and set(schema) <= KEYWORDS, "unsupported_schema_keyword")
        if "$ref" in schema:
            require(set(schema) <= {"$ref", *ANNOTATIONS}, "reference_sibling_not_supported")
            self.reference(schema["$ref"])
        if "type" in schema:
            value = schema["type"]
            require(isinstance(value, str) and value in {*SCALARS, "array", "object"}
                    or isinstance(value, list) and bool(value) and len(value) == len(set(value))
                    and all(isinstance(part, str) and part in {*SCALARS, "array", "object"} for part in value), "unsupported_schema_type")
        for key in ("oneOf", "anyOf", "allOf"):
            if key in schema:
                require(isinstance(schema[key], list) and bool(schema[key]), "empty_schema_composition")
                for part in schema[key]:
                    self.validate(part, depth + 1)
        require(sum(key in schema for key in ("oneOf", "anyOf", "allOf")) <= 1, "mixed_schema_composition")
        if "properties" in schema:
            require(isinstance(schema["properties"], dict), "invalid_properties")
            for name, part in schema["properties"].items():
                identifier(name)
                self.validate(part, depth + 1)
        if "required" in schema:
            required = schema["required"]
            require(isinstance(required, list) and len(required) == len(set(required)) and all(name in schema.get("properties", {}) for name in required), "invalid_required_properties")
        if "additionalProperties" in schema:
            additional = schema["additionalProperties"]
            require(type(additional) is bool or isinstance(additional, dict), "unsupported_additional_properties")
            if isinstance(additional, dict):
                self.validate(additional, depth + 1)
            require(not isinstance(additional, dict) or not schema.get("properties"), "typed_additional_properties_with_known_fields")
        if "items" in schema:
            self.validate(schema["items"], depth + 1)
        if "enum" in schema:
            require(isinstance(schema["enum"], list) and bool(schema["enum"])
                    and all(type(value) in (str, int, bool, type(None)) for value in schema["enum"]), "unsupported_enum")
        if "const" in schema:
            require(type(schema["const"]) in (str, int, bool, type(None)), "unsupported_const")

    def reference(self, ref: object) -> str:
        require(isinstance(ref, str) and re.fullmatch(r"#/components/schemas/[A-Za-z][A-Za-z0-9_]*", ref), "unsupported_model_reference")
        name = ref.rsplit("/", 1)[1]
        require(name in self.schemas, "missing_model_reference")
        return identifier(name)

    def object_schema(self, schema: dict, chain: tuple[str, ...] = ()) -> dict | None:
        if "$ref" in schema:
            name = self.reference(schema["$ref"])
            require(name not in chain, "recursive_object_intersection")
            return self.object_schema(self.schemas[name], (*chain, name))
        if "allOf" in schema:
            parts = [self.object_schema(part, chain) for part in schema["allOf"]]
            if any(part is None for part in parts):
                return None
            merged = {"type": "object", "properties": {}, "required": []}
            for part in parts:
                for name, value in part.get("properties", {}).items():
                    if name in merged["properties"]:
                        before = {k: v for k, v in merged["properties"][name].items() if k not in ANNOTATIONS}
                        after = {k: v for k, v in value.items() if k not in ANNOTATIONS}
                        require(before == after, "conflicting_object_intersection")
                    merged["properties"][name] = value
                merged["required"] = list(dict.fromkeys([*merged["required"], *part.get("required", [])]))
                require(part.get("additionalProperties", True) is not False, "closed_object_intersection_not_supported")
            return merged
        return schema if schema.get("type") == "object" else None

    def string_shape(self, schema: dict) -> bool:
        if schema.get("type") == "string":
            return True
        return any(key in schema for key in ("anyOf", "oneOf")) and all(
            self.string_shape(part) for part in schema.get("anyOf", schema.get("oneOf", [])))

    def annotation(self, schema: dict, hint: str) -> str:
        self.validate(schema)
        if "$ref" in schema:
            return self.reference(schema["$ref"])
        for key in ("oneOf", "anyOf"):
            if key in schema:
                return " | ".join(dict.fromkeys(self.annotation(part, f"{hint}Variant{index + 1}") for index, part in enumerate(schema[key])))
        if "allOf" in schema:
            merged = self.object_schema(schema)
            if merged is not None:
                return self.object_annotation(merged, hint)
            require(all(self.string_shape(part) for part in schema["allOf"]), "unsupported_scalar_intersection")
            return "str"
        if "enum" in schema or "const" in schema:
            values = schema.get("enum", [schema.get("const")])
            return "Literal[" + ", ".join(repr(value) for value in values) + "]"
        schema_type = schema.get("type")
        if isinstance(schema_type, list):
            return " | ".join(dict.fromkeys(self.annotation({**schema, "type": part}, f"{hint}Value") for part in schema_type))
        if schema_type in SCALARS:
            return SCALARS[schema_type]
        if schema_type == "array":
            require("items" in schema, "array_items_required")
            return f"list[{self.annotation(schema['items'], hint + 'Item')}]"
        if schema_type == "object":
            return self.object_annotation(schema, hint)
        require(not schema or set(schema) <= ANNOTATIONS, "untyped_schema_constraints")
        return "JsonValue"

    def object_annotation(self, schema: dict, name: str) -> str:
        identifier(name)
        if not schema.get("properties") and schema.get("additionalProperties", True) is not False:
            additional = schema.get("additionalProperties", {})
            return f"dict[str, {self.annotation(additional, name + 'Additional') if isinstance(additional, dict) else 'JsonValue'}]"
        if name in self.claims:
            require(self.claims[name] == schema, "generated_name_collision")
            return name
        require(name not in self.schemas or self.schemas[name] == schema or name in self.active, "generated_component_collision")
        self.claims[name] = schema
        fields = []
        for key, value in schema.get("properties", {}).items():
            annotation = self.annotation(value, name + pascal(key))
            # Quote forward expressions while evaluating NotRequired itself.
            # A future-annotations string around NotRequired prevents Python
            # 3.12 TypedDict from reporting its required keys correctly.
            annotation = repr(annotation)
            if key not in schema.get("required", []):
                annotation = f"NotRequired[{annotation}]"
            fields.append(f"    {identifier(key)}: {annotation}")
        self.definitions[name] = f"class {name}(TypedDict):\n" + ("\n".join(fields) if fields else "    pass") + "\n"
        return name

    def component(self, name: str) -> None:
        self.active.add(name)
        annotation = self.annotation(self.schemas[name], name)
        if annotation != name:
            require(name not in self.definitions, "generated_component_collision")
            self.definitions[name] = f"type {name} = {annotation}\n"
        self.active.remove(name)


def render(document: dict, cohort: dict) -> dict[str, bytes]:
    require(document.get("openapi") == "3.1.0" and document["servers"][0]["url"] == cohort["baseUrl"], "python_contract_drift")
    require(list(document["paths"]) == cohort["paths"] and len(cohort["paths"]) == 11, "python_cohort_paths")
    schemas = document.get("components", {}).get("schemas", {})
    require(isinstance(schemas, dict) and bool(schemas), "python_schemas_missing")
    renderer = Renderer(schemas)
    for name in schemas:
        identifier(name)
        renderer.component(name)
    operations = {}
    methods = []
    for path, item in document["paths"].items():
        require(set(item) <= {"get", "parameters"} and "get" in item, "python_get_only")
        operation = item["get"]
        require(not any(key in operation for key in ("requestBody", "servers")), "python_operation_shape")
        operation_id = identifier(operation["operationId"])
        name = snake(operation_id)
        require(name not in {"read", "pages", "aclose"} and name not in {method["name"] for method in methods}, "python_method_collision")
        parameters = [*item.get("parameters", []), *operation.get("parameters", [])]
        require(all(isinstance(p, dict) and p.get("in") in {"path", "query"} and type(p.get("required")) is bool and "schema" in p and "$ref" not in p for p in parameters), "python_parameter_shape")
        require(len({(p["in"], p["name"]) for p in parameters}) == len(parameters), "python_parameter_override")
        input_name = pascal(operation_id) + "Input"
        props = {}
        for location in ("path", "query"):
            selected = [p for p in parameters if p["in"] == location]
            if selected:
                require(location != "path" or all(p["required"] for p in selected), "python_path_required")
                props[location] = {"type": "object", "properties": {p["name"]: p["schema"] for p in selected}, "required": [p["name"] for p in selected if p["required"]], "additionalProperties": False}
        input_schema = {"type": "object", "properties": props, "required": [key for key, value in props.items() if value.get("required")], "additionalProperties": False}
        renderer.object_annotation(input_schema, input_name)
        response_schema = operation["responses"]["200"]["content"]["application/json"]["schema"]
        response_name = pascal(operation_id) + "Response"
        annotation = renderer.annotation(response_schema, response_name)
        if annotation != response_name:
            renderer.definitions[response_name] = f"type {response_name} = {annotation}\n"
        operations[operation_id] = {"path": path, "parameters": copy.deepcopy(parameters)}
        methods.append({"name": name, "operation_id": operation_id, "input": input_name, "response": response_name,
                        "input_required": any(p["required"] for p in parameters)})
    require(tuple(operations) == IDS, "python_operation_identity")
    models = BANNER + "from typing import Literal, NotRequired, TypedDict\n\n"
    models += "# Runtime responses retain arbitrary JSON; these annotations do not validate or coerce it.\n"
    models += "type JsonValue = None | bool | int | float | str | list[JsonValue] | dict[str, JsonValue]\n\n"
    models += "\n".join(renderer.definitions.values())
    client = BANNER + "from __future__ import annotations\n\nfrom typing import cast\n\nfrom ..runtime import UNSET, UnsetType, ReadResult, ReadRuntime, RequestOptions\nfrom . import models\n\n\nclass BotaApiClient(ReadRuntime):\n"
    client += "    \"\"\"Eleven generated async reads over the maintained transport and policy runtime.\"\"\"\n"
    client += "\n    # The raw-JSON-to-contract assertion preserves the result object and does not\n    # validate or coerce response bodies. No second transport is introduced.\n"
    for method in methods:
        argument = f"input: models.{method['input']}" + ("" if method["input_required"] else " | UnsetType = UNSET")
        client += f"\n    async def {method['name']}(self, {argument}, options: RequestOptions | UnsetType = UNSET) -> ReadResult[models.{method['response']}]:\n"
        client += f"        return cast('ReadResult[models.{method['response']}]', cast(object, await self.read({method['operation_id']!r}, input, options)))\n"
    metadata = BANNER + "BASE_URL = " + repr(cohort["baseUrl"]) + "\nOPERATION_IDS = " + repr(IDS) + "\nOPERATIONS = " + pprint.pformat(operations, sort_dicts=True, width=110) + "\n"
    return {"__init__.py": BANNER.encode(), "models.py": models.encode(), "client.py": client.encode(),
            "operations.py": metadata.encode(), "methods.json": json_bytes(methods)}


def load_inputs() -> tuple[dict, dict, dict[str, str]]:
    inputs = {}
    blobs = {}
    for name, expected in PINS.items():
        path = TYPESCRIPT / name
        require(path.is_file() and not path.is_symlink(), "nonregular_python_generation_input")
        blobs[name] = path.read_bytes()
        inputs[name] = digest(blobs[name])
        require(inputs[name] == expected, "pinned_python_input_drift")
    cohort = json.loads(blobs["cohort.json"])
    require(cohort["source"]["commit"] == "0eaaa8a516deb9c56054ecaf78ddf95803d016b7", "python_source_commit_drift")
    source = gzip.decompress(blobs["source-openapi.json.gz"])
    require(len(source) <= 5 * 1024 * 1024 and digest(source) == cohort["source"]["sha256"], "python_source_digest")
    require(json_bytes(project(json.loads(source), cohort)) == blobs["input.json"], "python_source_projection")
    require(inputs["input.json"] == cohort["projectionSha256"], "python_projection_digest")
    corpus = json.loads(blobs["conformance/corpus.json"])
    require(len(corpus["cases"]) == 94 and corpus["policyId"] == "private-eleven-read-policy-v1", "python_fixture_scope")
    return json.loads(blobs["input.json"]), cohort, inputs


def generate(check: bool = False) -> None:
    document, cohort, inputs = load_inputs()
    files = render(document, cohort)
    provenance = {"version": 1, "status": "python-eleven-read-generated-not-qualified", "source": cohort["source"],
                  "generatorSha256": digest(Path(__file__).read_bytes()), "inputs": inputs,
                  "operationCount": 11, "sharedFixtureCount": 94, "outputs": {name: digest(value) for name, value in files.items()},
                  "limitations": "Bounded annotation generator; no response validation, runtime test pass, Python parity or publication is established by these digests."}
    files["provenance.json"] = json_bytes(provenance)
    if check:
        for name, value in files.items():
            require((OUTPUT / name).is_file() and not (OUTPUT / name).is_symlink()
                    and (OUTPUT / name).read_bytes() == value, "python_generated_drift")
    else:
        OUTPUT.mkdir(parents=True, exist_ok=True)
        require(not OUTPUT.is_symlink(), "unsafe_python_generated_directory")
        for name, value in files.items():
            require(not (OUTPUT / name).is_symlink(), "unsafe_python_generated_target")
            (OUTPUT / name).write_bytes(value)
    print("Verified" if check else "Generated", "eleven Python reads and bound 94 unchanged synthetic fixtures")


